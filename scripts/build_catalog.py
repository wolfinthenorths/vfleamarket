"""Keep the browser and independently checked Apps Script price book in sync."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
path = ROOT / "public/catalog.json"
catalog = json.loads(path.read_text())
shops = [{"id": s["id"], "name": s["name"], "items": [{"id": i["id"], "name": i["name"], "price": i["price"], "slots": i["slots"]} for i in s["items"]]} for s in catalog["shops"]]
raw = json.dumps(shops, ensure_ascii=False, separators=(",", ":"))
revision = hashlib.sha256(raw.encode()).hexdigest()[:16]
catalog["revision"] = revision
path.write_text(json.dumps(catalog, ensure_ascii=False, indent=2))
# Category metadata is for inventory placement, outside the financial revision.
categories = {i["id"]: i["category"] for s in catalog["shops"] for i in s["items"]}
data = {"revision": revision, "shops": [{**s, "items": [{**i, "category": categories[i["id"]]} for i in s["items"]]} for s in shops]}
(ROOT / "google/catalog.gs").write_text("/** Generated by scripts/build_catalog.py; no external-request permission. */\nconst FM_CATALOG_DATA = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n")
print("Catalog revision:", revision)
